import test from 'node:test';
import assert from 'node:assert/strict';
import { spawn, execFile, execFileSync } from 'node:child_process';
import { promisify } from 'node:util';
import { createHash } from 'node:crypto';
import { chmod, mkdtemp, mkdir, readFile, realpath, rm, stat, symlink, writeFile } from 'node:fs/promises';
import http from 'node:http';
import os from 'node:os';
import path from 'node:path';
import { setTimeout as delay } from 'node:timers/promises';
import { resolveWorkspace } from '../src/hub-workspace.mjs';
import { chromium } from 'playwright-core';

const cli = path.resolve('bin/lavish-kit');
test('hub foreground owner rejects duplicates and stops without a relay', async t => {
  const dir = await mkdtemp(path.join(os.tmpdir(), 'hub-owner-'));
  t.after(() => rm(dir, { recursive: true, force: true }));
  const repo = path.join(dir, 'repo'), state = path.join(dir, 'lavish'), data = path.join(dir, 'data');
  await mkdir(repo); await mkdir(state);
  execFileSync('jj', ['git', 'init', repo]);
  const canonicalState = await realpath(state);
  let pollMode = 'waiting', polls = 0;
  const server = http.createServer((req, res) => {
    res.setHeader('content-type', 'application/json');
    if (req.url === '/health') res.end(JSON.stringify({ ok: true, app: 'lavish-axi', version: '0.1.97', lavish_kit_page_reviews: 1, state_id: createHash('sha256').update(path.join(canonicalState, 'state.json')).digest('hex').slice(0, 16) }));
    else {
      polls++;
      if (pollMode === 'feedback') { pollMode = 'waiting'; res.end(JSON.stringify({ status: 'feedback', prompts: ['Review this'], dom_snapshot: 'quoted context' })); }
      else if (pollMode === 'truncated') { res.write('{"status":"feedback"'); res.destroy(); }
      else setTimeout(() => res.end(JSON.stringify({ status: 'waiting' })), 50);
    }
  });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(() => server.closeAllConnections() || server.close());
  const stub = path.join(dir, 'lavish-axi');
  await writeFile(stub, '#!/bin/sh\nprintf "url: http://localhost:123/review\\n"\n'); await chmod(stub, 0o700);
  const opener = path.join(dir, process.platform === 'darwin' ? 'open' : 'xdg-open');
  await writeFile(opener, `#!/bin/sh\nprintf '%s\\n' "$1" >> "${dir}/opened"\n`); await chmod(opener, 0o700);
  const env = { ...process.env, PATH: `${dir}:${process.env.PATH}`, LAVISH_AXI_STATE_DIR: state, LAVISH_AXI_PORT: String(server.address().port), XDG_DATA_HOME: data, XDG_STATE_HOME: path.join(dir, 'xdg-state') };
  delete env.HC_TERMINAL_ID;
  const identity = await resolveWorkspace(repo, env), runtime = path.join(identity.directory, 'owner', 'runtime.json');
  const ownerScript = `import { runHubOwner } from ${JSON.stringify(new URL('../src/hub-runtime.mjs', import.meta.url).href)}; process.exitCode = await runHubOwner({ workspace: process.argv[1] }, { prepare: async (_page, options) => { if (!options.vendored) throw Error('expected vendored'); return { url: 'http://localhost:123/review' }; } });`;
  const ownerArgs = ['--input-type=module', '-e', ownerScript, repo];
  const owner = spawn(process.execPath, ownerArgs, { env, stdio: ['ignore', 'pipe', 'pipe'] });
  let stderr = '', output = ''; owner.stderr.on('data', chunk => { stderr += chunk; }); owner.stdout.on('data', chunk => { output += chunk; });
  t.after(() => { if (owner.exitCode === null) owner.kill('SIGKILL'); });
  for (let i = 0; i < 400; i++) { try { await stat(runtime); break; } catch { if (owner.exitCode !== null) throw new Error(stderr); await delay(30); } }
  assert.equal((await stat(runtime)).mode & 0o777, 0o600);
  const execute = promisify(execFile);
  const run = (file, args, options) => execute(file, args, { ...options, timeout: 5000 });
  await assert.rejects(run(process.execPath, [cli, 'hub', 'listen', '--workspace', repo], { env }), /hub owner is already running/i);
  const { stdout } = await run(process.execPath, [cli, 'hub', '--workspace', repo], { env });
  assert.match(stdout, /Hub owner running/);
  const subdir = path.join(repo, 'subdir'); await mkdir(subdir);
  assert.match((await run(process.execPath, [cli, 'hub'], { env, cwd: subdir })).stdout, /Hub owner running/);
  const other = path.join(dir, 'other'); await mkdir(other); execFileSync('jj', ['git', 'init', other]);
  await assert.rejects(run(process.execPath, [cli, 'hub', '--workspace', other], { env }), /No live hub owner/);
  const connection = JSON.parse(await readFile(runtime, 'utf8'));
  const request = async (operation, body = {}) => {
    const response = await fetch(`${connection.url}/action`, { method: 'POST', headers: { 'content-type': 'application/json', 'x-lavish-capability': connection.capability }, body: JSON.stringify({ operation, ...body }) });
    assert.equal(response.status, 200);
    return (await response.json()).result;
  };
  assert.equal((await request('status')).selected, 'commits');
  await run(process.execPath, [cli, 'hub', '--workspace', repo, '--view', 'tasks'], { env });
  assert.equal((await request('status')).selected, 'tasks');
  await run(process.execPath, [cli, 'hub', '--workspace', repo, '--open'], { env });
  const inside = path.join(repo, 'inside.html');
  await writeFile(inside, '<input aria-label="Frame draft"><p>original</p>');
  await writeFile(path.join(repo, 'asset.css'), 'original');
  const browser = await chromium.launch({ executablePath: process.env.LAVISH_KIT_CHROMIUM || chromium.executablePath(), headless: true });
  t.after(() => browser.close());
  const browserPage = await browser.newPage();
  await browserPage.goto(`file://${path.join(identity.directory, 'hub.html')}`);
  await browserPage.getByRole('button', { name: 'Tasks', exact: true }).waitFor();
  const taskDraft = browserPage.getByRole('textbox', { name: 'Tasks Markdown' });
  await taskDraft.fill('Unsaved task');
  await run(process.execPath, [cli, 'hub', 'publish', inside, '--id', 'inside', '--workspace', repo], { env });
  const sibling = (await request('documents')).documents.find(doc => doc.id === 'inside').sibling;
  assert.match(await readFile(path.join(identity.directory, sibling), 'utf8'), /original/);
  await browserPage.getByText('Navigation paused: unsaved drafts remain on this page.').waitFor();
  assert.equal(await taskDraft.inputValue(), 'Unsaved task');
  browserPage.once('dialog', dialog => dialog.dismiss());
  await browserPage.getByRole('button', { name: 'inside.html', exact: true }).click();
  assert.equal(await taskDraft.inputValue(), 'Unsaved task');
  browserPage.once('dialog', dialog => { assert.equal(dialog.type(), 'beforeunload'); return dialog.dismiss(); });
  await browserPage.reload().catch(() => {});
  assert.equal(await taskDraft.inputValue(), 'Unsaved task');
  const siblingPage = await browser.newPage();
  await siblingPage.goto(`file://${path.join(identity.directory, sibling)}`);
  await siblingPage.getByRole('link', { name: 'Changes', exact: true }).click();
  await siblingPage.getByRole('button', { name: 'Changes', exact: true }).waitFor();
  assert.equal((await request('status')).selected, 'changes');
  await run(process.execPath, [cli, 'hub', '--workspace', repo, '--view', 'inside'], { env });
  await siblingPage.getByLabel('Frame draft').fill('Authored draft');
  siblingPage.once('dialog', dialog => dialog.dismiss());
  await siblingPage.getByRole('link', { name: 'Tasks', exact: true }).click();
  assert.equal(await siblingPage.getByLabel('Frame draft').inputValue(), 'Authored draft');
  await run(process.execPath, [cli, 'hub', '--workspace', repo, '--view', 'tasks'], { env });
  await delay(2300);
  assert.equal(await siblingPage.getByLabel('Frame draft').inputValue(), 'Authored draft');
  siblingPage.once('dialog', dialog => dialog.accept());
  await siblingPage.getByRole('link', { name: 'Tasks', exact: true }).click();
  await siblingPage.getByRole('textbox', { name: 'Tasks Markdown' }).waitFor();
  await siblingPage.close();
  await writeFile(inside, '<p>externally updated</p>');
  await run(process.execPath, [cli, 'hub', 'publish', inside, '--id', 'inside', '--workspace', repo], { env });
  assert.match(await readFile(path.join(identity.directory, sibling), 'utf8'), /externally updated/);
  const outsideHtml = path.join(dir, 'outside.html');
  await writeFile(outsideHtml, '<p>outside</p>');
  await writeFile(path.join(dir, 'outside.css'), 'outside');
  await symlink(path.join(repo, 'asset.css'), path.join(dir, 'linked.css'));
  await run(process.execPath, [cli, 'hub', 'publish', outsideHtml, '--id', 'outside', '--workspace', repo, '--open'], { env });
  assert.equal((await readFile(path.join(dir, 'opened'), 'utf8')).trim().split('\n').length, 2);
  const document = path.join(dir, 'review.md'); await writeFile(document, '# Review\n');
  const metadata = path.join(dir, 'metadata.json');
  await writeFile(metadata, JSON.stringify({ reviewedRepository: 'Reviewed repo', baseCommit: 'a'.repeat(40), headCommit: 'b'.repeat(40) }));
  await run(process.execPath, [cli, 'hub', 'publish', document, '--id', 'review', '--metadata-file', metadata, '--workspace', repo], { env });
  assert.equal((await request('status')).selected, 'review');
  assert.equal((await request('documents')).documents.find(doc => doc.id === 'review').metadata.reviewedRepository, 'Reviewed repo');
  await writeFile(metadata, JSON.stringify({ unknown: 'invalid' }));
  await assert.rejects(run(process.execPath, [cli, 'hub', 'publish', document, '--id', 'review', '--metadata-file', metadata, '--workspace', repo], { env }), /metadata/i);
  assert.equal((await request('documents')).documents.find(doc => doc.id === 'review').metadata.reviewedRepository, 'Reviewed repo');
  await run(process.execPath, [cli, 'hub', 'publish', document, '--id', 'review', '--workspace', repo], { env });
  assert.deepEqual((await request('documents')).documents.find(doc => doc.id === 'review').metadata, {});
  const reviewedScope = { reviewedRepository: 'Reviewed repo', baseCommit: 'a'.repeat(40), headCommit: 'b'.repeat(40), sourceUrl: 'https://example.com/review' };
  await writeFile(metadata, JSON.stringify(reviewedScope));
  await run(process.execPath, [cli, 'hub', 'publish', outsideHtml, '--id', 'outside', '--metadata-file', metadata, '--workspace', repo], { env });
  await run(process.execPath, [cli, 'hub', 'publish', document, '--id', 'review', '--metadata-file', metadata, '--workspace', repo], { env });
  assert.deepEqual((await request('documents')).documents.find(doc => doc.id === 'review').metadata, reviewedScope);
  assert.equal(output, '');
  pollMode = 'feedback';
  for (let i = 0; i < 100 && !output.includes('\n'); i++) await delay(30);
  const notification = JSON.parse(output.trim());
  assert.equal(notification.type, 'agent-notification');
  assert.deepEqual(notification.prompts, ['Review this']);
  assert.equal(notification.context, 'quoted context');
  assert.match(notification.reply, /lavish-axi reply/);
  const ownerExit = new Promise(resolve => owner.once('exit', resolve));
  await run(process.execPath, [cli, 'hub', 'stop', '--workspace', repo], { env });
  const exit = await ownerExit;
  assert.equal(exit, 0, stderr);
  await assert.rejects(readFile(runtime), { code: 'ENOENT' });
  await assert.rejects(stat(path.join(env.XDG_STATE_HOME, 'lavish-kit', 'relay.json')), { code: 'ENOENT' });

  await rm(repo, { recursive: true, force: true });
  const restarted = spawn(process.execPath, ownerArgs, { env, stdio: ['ignore', 'pipe', 'pipe'] });
  let restartError = ''; restarted.stderr.on('data', chunk => { restartError += chunk; });
  t.after(() => { if (restarted.exitCode === null) restarted.kill('SIGKILL'); });
  for (let i = 0; i < 100; i++) { try { await stat(runtime); break; } catch { if (restarted.exitCode !== null) throw new Error(restartError); await delay(30); } }
  const second = JSON.parse(await readFile(runtime, 'utf8'));
  const secondRequest = async (operation, body = {}) => {
    const response = await fetch(`${second.url}/action`, { method: 'POST', headers: { 'content-type': 'application/json', 'x-lavish-capability': second.capability }, body: JSON.stringify({ operation, ...body }) });
    return { status: response.status, ...(await response.json()) };
  };
  assert.equal((await secondRequest('status')).result.selected, 'commits');
  assert.equal((await secondRequest('status')).result.available, false);
  assert.equal((await secondRequest('readDocument', { id: 'review' })).result.text, '# Review\n');
  const restartedDocuments = (await secondRequest('documents')).result.documents;
  assert.deepEqual(restartedDocuments.find(doc => doc.id === 'review').metadata, reviewedScope);
  const outsideSibling = restartedDocuments.find(doc => doc.id === 'outside').sibling;
  const siblingHtml = await readFile(path.join(identity.directory, outsideSibling), 'utf8');
  assert.match(siblingHtml, /aria-label="Reviewed scope"/);
  for (const value of Object.values(reviewedScope)) assert.ok(siblingHtml.includes(value));
  assert.notEqual((await secondRequest('readDocument', { id: 'inside' })).status, 200);
  await mkdir(repo); execFileSync('jj', ['git', 'init', repo]);
  await writeFile(inside, '<p>replacement</p>');
  await writeFile(path.join(repo, 'asset.css'), 'replacement');
  assert.notEqual((await secondRequest('readDocument', { id: 'inside' })).status, 200);
  assert.equal((await secondRequest('readDocument', { id: 'outside' })).result.text, '<p>outside</p>');
  const html = await readFile(second.page, 'utf8');
  const key = html.match(/"resourceKey":"([a-f0-9]+)"/)[1];
  const resource = (id, name) => fetch(`${second.url}/resources/${key}/${id}/${name}`);
  assert.equal((await resource('inside', 'asset.css')).status, 404);
  assert.equal((await resource('outside', 'linked.css')).status, 404);
  assert.equal(await (await resource('outside', 'outside.css')).text(), 'outside');
  assert.equal((await secondRequest('status')).result.available, false);
  assert.notEqual((await secondRequest('snapshot')).status, 200);
  assert.notEqual((await secondRequest('saveDocument', { id: 'review', text: 'changed' })).status, 200);
  assert.equal(await readFile(document, 'utf8'), '# Review\n');
  const restartExit = new Promise(resolve => restarted.once('exit', resolve));
  pollMode = 'truncated';
  assert.notEqual(await restartExit, 0, restartError);
  const stoppedPolls = polls;
  await delay(150);
  assert.equal(polls, stoppedPolls, 'ambiguous poll must not be retried');
  await assert.rejects(readFile(runtime), { code: 'ENOENT' });
  await assert.rejects(run(process.execPath, [cli, 'hub', '--workspace', repo], { env }), /No live hub owner/);
});
