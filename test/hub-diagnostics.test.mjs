import test from 'node:test';
import assert from 'node:assert/strict';
import http from 'node:http';
import { EventEmitter } from 'node:events';
import express from 'express';
import { createHubTransport } from '../src/hub-transport.mjs';
import { createHubProxy } from '../vendor/lavish/src/hub-proxy.js';

test('opt-in diagnostics trace action lifecycle without request data', async t => {
  const lines = [];
  const previous = process.env.LAVISH_HUB_DIAGNOSTICS;
  process.env.LAVISH_HUB_DIAGNOSTICS = '1';
  const original = console.error;
  console.error = line => lines.push(line);
  t.after(() => { console.error = original; if (previous === undefined) delete process.env.LAVISH_HUB_DIAGNOSTICS; else process.env.LAVISH_HUB_DIAGNOSTICS = previous; });
  let entered, release;
  const started = new Promise(resolve => { entered = resolve; });
  const held = new Promise(resolve => { release = resolve; });
  const transport = await createHubTransport({ save: async () => 'ok', hold: async () => { entered(); await held; return 'ok'; } });
  t.after(() => transport.close());
  const key = 'a'.repeat(16);
  const app = express();
  const proxy = createHubProxy({ store: { findByKey: async () => ({ status: 'open' }) }, events: new EventEmitter(), jsonParser: express.json() });
  app.post('/register', proxy.control, proxy.register);
  app.use('/hub-proxy', proxy.handle);
  const server = http.createServer(app);
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(() => new Promise(resolve => { server.close(resolve); server.closeAllConnections(); }));
  const base = `http://127.0.0.1:${server.address().port}`;
  await fetch(`${base}/register`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ key, port: Number(new URL(transport.url).port), capability: transport.capability, resourceKey: transport.resourceKey, identityKey: transport.identityKey }) });
  const url = `${base}/hub-proxy/${key}/action`;
  assert.equal((await fetch(url, { method: 'OPTIONS', headers: { origin: 'null', 'access-control-request-method': 'POST', 'access-control-request-headers': 'content-type,x-lavish-capability' } })).status, 204);
  assert.equal((await fetch(url, { method: 'POST', headers: { origin: 'null', 'content-type': 'application/json', 'x-lavish-capability': transport.capability }, body: JSON.stringify({ operation: 'save', secret: 'body-sensitive' }) })).status, 200);
  const controller = new AbortController();
  const pending = fetch(url, { method: 'POST', headers: { origin: 'null', 'content-type': 'application/json', 'x-lavish-capability': transport.capability }, body: JSON.stringify({ operation: 'hold' }), signal: controller.signal }).catch(() => {});
  await started;
  const closed = new Promise(resolve => {
    const check = setInterval(() => { if (lines.some(line => line.includes('"side":"owner"') && line.includes('"event":"close"') && line.includes('"id":2'))) { clearInterval(check); resolve(); } }, 5);
    check.unref();
  });
  controller.abort();
  await pending;
  await Promise.race([closed, new Promise((_, reject) => setTimeout(() => reject(new Error('close not observed')), 2000))]);
  release();
  const before = lines.length;
  delete process.env.LAVISH_HUB_DIAGNOSTICS;
  assert.equal((await fetch(url, { method: 'OPTIONS', headers: { origin: 'null', 'access-control-request-method': 'POST' } })).status, 204);
  assert.equal(lines.length, before);
  const text = lines.join('\n');
  for (const expected of ['proxy', 'owner', 'OPTIONS', 'POST', 'forward', 'finish']) assert.ok(text.includes(expected), expected);
  for (const forbidden of [key, transport.capability, transport.resourceKey, transport.identityKey, 'body-sensitive', '/action']) assert.ok(!text.includes(forbidden), forbidden);
});
